def main() -> None:
    out = Path(__file__).resolve().parents[1] / "evals" / "datasets" / "hongloumeng_recall.jsonl"
    lines = []
    for cid, category, query, chapter, chunk, quote, notes in ROWS:
        lines.append(json.dumps({
            "id": cid,
            "category": category,
            "query": query,
            "file_id": FILE_ID,
            "gold_chunks": [{
                "chapter_no": chapter,
                "chunk_no": chunk,
                "relevance": 2,
                "evidence_quote": quote,
            }],
            "gold_chapters": [chapter],
            "notes": notes,
        }, ensure_ascii=False))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"已写入 {len(lines)} 题 -> {out}")

    # 自检：id 唯一、章节/片段号为正、片段不重复
    ids = [r[0] for r in ROWS]
    chunks = [(r[3], r[4]) for r in ROWS]
    assert len(set(ids)) == len(ids), "id 重复"
    assert len(set(chunks)) == len(chunks), "金标片段重复"
    assert all(c >= 0 and n > 0 for c, n in chunks), "章节/片段号非法"
    from collections import Counter
    print("分类分布:", dict(Counter(r[1] for r in ROWS)))
    print("覆盖章节数:", len({r[3] for r in ROWS}))


if __name__ == "__main__":
    main()
